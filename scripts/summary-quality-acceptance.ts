const usage = `Usage:
  bun scripts/summary-quality-acceptance.ts seed --mode local-development --workspace-id <uuid> --actor-id <uuid>
  bun scripts/summary-quality-acceptance.ts collect --mode local-development --workspace-id <uuid> --actor-id <uuid> --case <case-id> --job-id <uuid> --out <new-artifact.json>

DATABASE_URL must explicitly name a loopback PostgreSQL server with no query parameters.
Seed adds four synthetic transcripts to an existing authenticated workspace.
Collect only reads a specified completed job and writes an exclusive, read-only artifact.
Neither action submits jobs, calls providers, provisions budgets, or creates audio.`;

export function localDatabaseUrl(value: string | undefined): string {
  if (!value) {
    throw new Error("DATABASE_URL is required.");
  }
  let url: URL;
  try {
    url = new URL(value);
  } catch {
    throw new Error("DATABASE_URL must be a valid local PostgreSQL URL.");
  }
  if (
    !["postgres:", "postgresql:"].includes(url.protocol) ||
    !["127.0.0.1", "localhost", "[::1]"].includes(url.hostname) ||
    url.search ||
    url.hash ||
    url.pathname.length <= 1
  ) {
    throw new Error("Only loopback PostgreSQL URLs without query parameters are allowed.");
  }
  return value;
}

function marker(fixture: SummaryQualityFixture) {
  return `${SEED_VERSION}/${fixture.id}/${summaryQualityDigest(fixture)}`;
}

// This is a derived evaluation fixture, never a replacement for the frozen one.
// The actual repository uses segment IDs as evidence IDs and job ID as snapshot ID.
export function applicationFixture(
  fixture: SummaryQualityFixture,
  workspaceId: string,
  jobId: string,
): SummaryQualityFixture {
  const evidenceIds = new Map(
    fixture.context.passages.map((passage) => [passage.evidenceId, passage.segmentId]),
  );
  const personIds = new Set(
    fixture.context.passages.flatMap((passage) =>
      passage.assignment.kind === "person" ? [passage.assignment.personId] : [],
    ),
  );
  const mapRubric = (items: SummaryQualityFixture["rubric"]["requiredFacts"]) =>
    items.map((item) => ({
      ...item,
      evidence: item.evidence.map((citation) => {
        const evidenceId = evidenceIds.get(citation.evidenceId);
        if (!evidenceId) {
          throw new Error("Frozen rubric contains an unmapped evidence ID.");
        }
        return { ...citation, evidenceId };
      }),
    }));
  return {
    id: `${fixture.id}/local-app-v1/${jobId}`,
    version: fixture.version,
    context: validateSummaryContext({
      ...fixture.context,
      workspaceId,
      snapshotId: jobId,
      passages: fixture.context.passages
        .map((passage) => ({
          ...passage,
          evidenceId: passage.segmentId,
        }))
        .sort(
          (left, right) =>
            left.sequence - right.sequence ||
            left.orderKey.localeCompare(right.orderKey) ||
            left.segmentId.localeCompare(right.segmentId),
        ),
      people: fixture.context.people
        .filter((person) => personIds.has(person.personId))
        .sort((left, right) => left.personId.localeCompare(right.personId)),
    }),
    rubric: {
      requiredFacts: mapRubric(fixture.rubric.requiredFacts),
      prohibitedInferences: mapRubric(fixture.rubric.prohibitedInferences),
    },
    // Authored controls were not generated by this job.
    controls: [],
  };
}

export function collectionPrompt(fixture: SummaryQualityFixture, promptVersion: string) {
  const prompt = resolveSummaryPrompt(promptVersion);
  const provenance = summaryQualityProvenance(fixture, promptVersion);
  if (provenance.promptVersion !== promptVersion) {
    throw new Error(
      `Quality evaluator does not support the job's registered prompt version: ${promptVersion}.`,
    );
  }
  return { prompt, provenance };
}

async function requireMembership(tx: Transaction, workspaceId: string, actorId: string) {
  const [member] = await tx
    .select({
      revokedAt: schema.workspaceMemberships.revokedAt,
      deletedAt: schema.workspaces.deletedAt,
    })
    .from(schema.workspaceMemberships)
    .innerJoin(schema.workspaces, eq(schema.workspaces.id, schema.workspaceMemberships.workspaceId))
    .where(
      and(
        eq(schema.workspaceMemberships.workspaceId, workspaceId),
        eq(schema.workspaceMemberships.userId, actorId),
      ),
    )
    .limit(1);
  if (!member || member.revokedAt || member.deletedAt) {
    throw new Error("Actor must already be an active member of the existing local workspace.");
  }
}

async function seedCase(
  tx: Transaction,
  fixture: SummaryQualityFixture,
  workspaceId: string,
  actorId: string,
) {
  const context = fixture.context;
  const source = context.source;
  const note = {
    workspaceId,
    id: source.noteId,
    revision: context.noteRevision,
    title: context.title,
    transcript: context.passages.map((passage) => passage.text).join("\n\n"),
    importSourceKey: marker(fixture),
    deletedAt: null,
    branchId: schema.DEFAULT_BRANCH,
  };
  const profiles = context.people.map((person) => ({
    workspaceId,
    id: person.personId,
    revision: person.revision,
    displayName: person.displayName,
    description: person.authoredDescription,
    accountId: null,
    deletedAt: null,
    branchId: schema.DEFAULT_BRANCH,
  }));
  const recording = {
    workspaceId,
    id: source.recordingId,
    noteId: source.noteId,
    actorId,
    // Explicit synthetic metadata: no real audio or provider artifact is asserted.
    sha256: summaryQualityDigest({ syntheticFixture: marker(fixture) }),
    bytes: 1,
    mimeType: "audio/wav",
    durationSeconds: Math.max(...context.passages.map((passage) => passage.endSeconds)),
    objectKey: `synthetic-summary-quality/${workspaceId}/${source.recordingId}/no-audio`,
    status: "ready" as const,
    deletedAt: null,
  };
  const run = {
    workspaceId,
    id: source.runId,
    noteId: source.noteId,
    recordingId: source.recordingId,
    actorId,
    status: "succeeded" as const,
    config: { model: SEED_VERSION, transcriptionModel: "synthetic-authored-transcript" },
    transcriptGeneration: source.generation,
    correctionsMaterializedAt: SEED_TIME,
    providerJobId: null,
    rawObjectKey: null,
    error: null,
  };
  const utterances = context.passages.map((passage) => ({
    workspaceId,
    id: passage.sourceUtteranceId,
    runId: source.runId,
    sequence: passage.sequence,
    startSeconds: passage.startSeconds,
    endSeconds: passage.endSeconds,
    speakerLabel: passage.providerTrackId,
    text: passage.text,
  }));
  const segments = context.passages.map((passage) => ({
    workspaceId,
    id: passage.segmentId,
    runId: source.runId,
    sourceUtteranceId: passage.sourceUtteranceId,
    parentId: null,
    sequence: passage.sequence,
    orderKey: passage.orderKey,
    active: true,
    revision: passage.segmentRevision,
    attributionRevision: passage.attributionRevision,
    startSeconds: passage.startSeconds,
    endSeconds: passage.endSeconds,
    text: passage.text,
    assignmentKind: passage.assignment.kind,
    personId: passage.assignment.kind === "person" ? passage.assignment.personId : null,
    assignmentSource: "manual" as const,
    reviewState: "confirmed" as const,
    providerScore: null,
    sampleSuitability: "not_evaluated" as const,
  }));

  const [existing] = await tx
    .select()
    .from(schema.notes)
    .where(and(eq(schema.notes.workspaceId, workspaceId), eq(schema.notes.id, source.noteId)))
    .for("update")
    .limit(1);
  if (!existing) {
    // Deliberately no upserts: any child identity collision rolls back all four cases.
    await tx.insert(schema.notes).values(note);
    await tx.insert(schema.people).values(profiles);
    await tx.insert(schema.recordings).values(recording);
    await tx.insert(schema.processingRuns).values(run);
    await tx.insert(schema.transcriptUtterances).values(utterances);
    await tx.insert(schema.transcriptSegments).values(segments);
  } else {
    if (existing.importSourceKey !== marker(fixture)) {
      throw new Error(`Fixture identity collision for ${fixture.id}; nothing was changed.`);
    }
    // Idempotence is verify-and-return, never repairing or resetting edited work.
    const groups = [
      [schema.notes, [note]],
      [schema.people, profiles],
      [schema.recordings, [recording]],
      [schema.processingRuns, [run]],
      [schema.transcriptUtterances, utterances],
      [schema.transcriptSegments, segments],
    ] as const;
    for (const [table, expected] of groups) {
      const rows = await tx
        .select()
        .from(table)
        .where(
          and(
            eq(table.workspaceId, workspaceId),
            inArray(
              table.id,
              expected.map((row) => row.id),
            ),
          ),
        );
      for (const row of expected) {
        const actual = rows.find((item) => item.id === row.id);
        if (
          !actual ||
          Object.entries(row).some(
            ([key, value]) => !isDeepStrictEqual(Reflect.get(actual, key), value),
          )
        ) {
          throw new Error(
            `Seeded ${fixture.id} was changed or is incomplete; refusing to overwrite.`,
          );
        }
      }
    }
  }
  return {
    caseId: fixture.id,
    title: context.title,
    workspaceId,
    noteId: source.noteId,
    runId: source.runId,
    outcome: existing ? "already-seeded" : "seeded",
    audio: "synthetic metadata only; playback is unavailable",
  };
}

async function collect(
  tx: Transaction,
  fixture: SummaryQualityFixture,
  workspaceId: string,
  actorId: string,
  jobId: string,
) {
  await requireMembership(tx, workspaceId, actorId);
  const [row] = await tx
    .select({ job: schema.analysisJobs, summary: schema.noteSummaries })
    .from(schema.analysisJobs)
    .innerJoin(
      schema.noteSummaries,
      and(
        eq(schema.noteSummaries.workspaceId, schema.analysisJobs.workspaceId),
        eq(schema.noteSummaries.jobId, schema.analysisJobs.id),
      ),
    )
    .where(
      and(
        eq(schema.analysisJobs.workspaceId, workspaceId),
        eq(schema.analysisJobs.id, jobId),
        eq(schema.analysisJobs.noteId, fixture.context.source.noteId),
      ),
    )
    .limit(1);
  if (!row || row.job.status !== "succeeded" || !row.job.context) {
    throw new Error("A completed, published job for this exact fixture is required.");
  }
  const { job, summary } = row;
  if (
    !job.policy.budgetId ||
    summary.provenance.promptVersion !== job.policy.promptVersion ||
    summary.provenance.model !== job.policy.model ||
    summary.provenance.schemaVersion !== job.policy.schemaVersion ||
    summary.provenance.policyVersion !== job.policy.version ||
    summary.snapshotId !== jobId ||
    summary.noteId !== fixture.context.source.noteId ||
    !isDeepStrictEqual(summary.source, fixture.context.source) ||
    !isDeepStrictEqual(job.source, fixture.context.source)
  ) {
    throw new Error(
      "Saved result provenance does not match the selected fixture and pinned policy.",
    );
  }
  const [reservation] = await tx
    .select()
    .from(schema.summaryInferenceReservations)
    .where(
      and(
        eq(schema.summaryInferenceReservations.workspaceId, workspaceId),
        eq(schema.summaryInferenceReservations.jobId, jobId),
        eq(schema.summaryInferenceReservations.budgetId, job.policy.budgetId),
      ),
    )
    .limit(1);
  if (!reservation) {
    throw new Error("The completed job has no reservation in its pinned persistent allowance.");
  }

  const derived = applicationFixture(fixture, workspaceId, jobId);
  const { prompt, provenance } = collectionPrompt(derived, job.policy.promptVersion);
  const body = JSON.stringify(derived.context);
  // The DB reference attests the exact bytes persisted by the app. A reconstruction
  // is accepted only on checksum equality; no R2/network access or guessed digest.
  await readSummarySnapshot(
    {
      get: () =>
        Promise.resolve({ size: Buffer.byteLength(body), text: () => Promise.resolve(body) }),
    },
    workspaceId,
    jobId,
    row.job.context,
    job.policy.maxContextBytes,
  );
  const submission: SummaryQualitySubmission = {
    submissionId: `${fixture.id}/${jobId}`,
    provenance,
    producer: {
      kind: "submitted-output",
      label: "Published local application Summary; checksum-verified synthetic fixture context.",
      model: summary.provenance.model,
      runId: jobId,
    },
    output: summary.analysis,
  };
  return {
    artifactVersion: SEED_VERSION,
    collectedAt: new Date().toISOString(),
    mapping: {
      frozenFixtureId: fixture.id,
      frozenFixtureDigest: summaryQualityDigest(fixture),
      frozenContextDigest: summaryQualityDigest(fixture.context),
      workspaceId: { frozen: fixture.context.workspaceId, actual: workspaceId },
      snapshotId: { frozen: fixture.context.snapshotId, actual: jobId },
      evidenceIds: fixture.context.passages.map((passage) => ({
        frozen: passage.evidenceId,
        actual: passage.segmentId,
      })),
      profiles: {
        selection:
          "Only assigned person IDs, ordered by ID, matching repository context preparation.",
        frozen: fixture.context.people.map((person) => person.personId),
        actual: derived.context.people.map((person) => person.personId),
        omitted: fixture.context.people
          .filter(
            (person) =>
              !derived.context.people.some((included) => included.personId === person.personId),
          )
          .map((person) => person.personId),
      },
      passageOrder:
        "Sequence, order key, then segment ID, matching repository context preparation.",
      unchanged:
        "Source IDs, generation, revisions, quotes, included profile contents, assignments, tracks and bounds.",
      contextVerification: "Reconstructed bytes match the completed job's pinned SHA-256 checksum.",
      controls: "Omitted from the derived fixture; not model output.",
    },
    fixture: derived,
    prompt: {
      ...prompt,
      renderedUser: prompt.user.replace("{{snapshot}}", () => body),
      verification:
        "Registered template resolved at collection using the completed job's pinned prompt version.",
    },
    execution: { job, summary, reservation },
    submission,
    evaluation: evaluateSummaryQuality(derived, submission),
  };
}

async function main() {
  const [action, ...args] = process.argv.slice(2);
  if (action === "--help" && args.length === 0) {
    console.log(usage);
    return;
  }
  if (action !== "seed" && action !== "collect") {
    throw new Error(usage);
  }
  const names =
    action === "seed"
      ? ["--mode", "--workspace-id", "--actor-id"]
      : ["--mode", "--workspace-id", "--actor-id", "--case", "--job-id", "--out"];
  const options = new Map<string, string>();
  for (let index = 0; index < args.length; index += 2) {
    const name = args[index]!;
    const value = args[index + 1];
    if (!names.includes(name) || options.has(name) || !value || value.startsWith("--")) {
      throw new Error(usage);
    }
    options.set(name, value);
  }
  if (options.size !== names.length || options.get("--mode") !== MODE) {
    throw new Error(usage);
  }
  const workspaceId = idSchema.parse(options.get("--workspace-id"));
  const actorId = idSchema.parse(options.get("--actor-id"));
  const fixture = summaryQualityFixtures.find((item) => item.id === options.get("--case"));
  const jobId = action === "collect" ? idSchema.parse(options.get("--job-id")) : null;
  if (action === "collect" && !fixture) {
    throw new Error("Unknown frozen fixture case ID.");
  }
  const client = postgres(localDatabaseUrl(process.env.DATABASE_URL), {
    max: 1,
    prepare: false,
    connect_timeout: 5,
  });
  const db = drizzle(client, { schema });
  try {
    if (action === "seed") {
      const result = await db.transaction(async (tx) => {
        await tx.execute(
          sql`select pg_advisory_xact_lock(hashtextextended(${`${SEED_VERSION}:${workspaceId}`}, 0))`,
        );
        await requireMembership(tx, workspaceId, actorId);
        const seeded = [];
        for (const item of summaryQualityFixtures) {
          seeded.push(await seedCase(tx, item, workspaceId, actorId));
        }
        return seeded;
      });
      console.log(JSON.stringify(result, null, 2));
    } else {
      const artifact = await db.transaction(
        (tx) => collect(tx, fixture!, workspaceId, actorId, jobId!),
        { isolationLevel: "repeatable read", accessMode: "read only" },
      );
      const output = options.get("--out")!;
      await writeFile(output, `${JSON.stringify(artifact, null, 2)}\n`, {
        flag: "wx",
        mode: 0o444,
      });
      console.log(
        JSON.stringify({
          artifact: output,
          submissionId: artifact.submission.submissionId,
          outputDigest: artifact.evaluation.outputDigest,
          semanticReview: artifact.evaluation.semanticReview.status,
        }),
      );
    }
  } finally {
    await client.end({ timeout: 5 });
  }
}

